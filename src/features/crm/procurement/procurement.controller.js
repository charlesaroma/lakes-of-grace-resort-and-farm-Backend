export const receiveProcurement = async (req, res) => {
  const existing = await prisma.procurementRequisition.findUnique({ where: { id: req.params.id } });
  if (!existing) return res.status(404).json({ message: 'Procurement requisition not found' });
  if (existing.status !== 'ordered') {
    return res.status(400).json({ message: 'Only ordered requisitions can be received' });
  }

  const { receiptUrls, unitPriceActual, surplusAction, surplusAmount, reallocatedTo } = req.body || {};
  const surplusQty = Math.max(0, parseInt(surplusAmount, 10) || 0);
  const actualUnit = unitPriceActual !== undefined ? parseFloat(unitPriceActual) : existing.unitPriceEstimated;

  if (surplusAction === 'reallocated' && !reallocatedTo) {
    return res.status(400).json({ message: 'reallocatedTo location is required when reallocating surplus' });
  }

  const record = await prisma.$transaction(async (tx) => {
    const receivedQty = surplusQty > 0
      ? Math.max(existing.quantityNeeded - surplusQty, 0)
      : existing.quantityNeeded;

    const sourceStock = await tx.stockItem.findUnique({ where: { id: existing.itemId } });
    if (!sourceStock) {
      throw Object.assign(new Error('Stock item for this requisition no longer exists'), { status: 400 });
    }

    const newQuantity = sourceStock.quantity + receivedQty;
    await tx.stockLedger.create({
      data: {
        itemId: sourceStock.id,
        item: sourceStock.item,
        type: 'restock',
        quantity: receivedQty,
        balance: newQuantity,
        department: sourceStock.locationId || 'central',
        purpose: `Procurement ${existing.reference}`,
        note: `Received ${receivedQty} ${existing.unit} (surplus ${surplusQty})`,
        userId: req.userId,
      },
    });
    await tx.stockItem.update({
      where: { id: sourceStock.id },
      data: { quantity: newQuantity },
    });

    let reallocation = null;
    if (surplusAction === 'reallocated' && surplusQty > 0 && reallocatedTo) {
      let target = await tx.stockItem.findFirst({
        where: { item: sourceStock.item, locationId: reallocatedTo },
      });
      if (!target) {
        target = await tx.stockItem.create({
          data: {
            item: sourceStock.item,
            category: sourceStock.category,
            unit: sourceStock.unit,
            quantity: 0,
            threshold: 0,
            parLevel: 0,
            perishable: false,
            locationId: reallocatedTo,
          },
        });
      }
      const targetQuantity = target.quantity + surplusQty;
      await tx.stockLedger.create({
        data: {
          itemId: target.id,
          item: target.item,
          type: 'adjustment',
          quantity: surplusQty,
          balance: targetQuantity,
          department: reallocatedTo,
          purpose: `Procurement surplus ${existing.reference}`,
          note: 'Reallocated surplus',
          userId: req.userId,
        },
      });
      await tx.stockItem.update({ where: { id: target.id }, data: { quantity: targetQuantity } });
      reallocation = { targetId: target.id, quantity: surplusQty };
    }

    if (surplusAction === 'returned_to_petty_cash' && surplusQty > 0) {
      const last = await tx.pettyCashLedger.findFirst({ orderBy: { createdAt: 'desc' } });
      await tx.pettyCashLedger.create({
        data: {
          type: 'surplus_returned',
          amount: surplusQty,
          balance: (last?.balance || 0) + surplusQty,
          requisitionId: existing.id,
          note: `Surplus from ${existing.reference}`,
          userId: req.userId,
        },
      });
    }

    if (existing.source === 'farm' && surplusQty > 0) {
      await tx.stockBatch.create({
        data: {
          itemId: sourceStock.id,
          item: sourceStock.item,
          quantity: surplusQty,
          source: 'farm',
          receivedDate: new Date(),
        },
      });
    }

    return tx.procurementRequisition.update({
      where: { id: existing.id },
      data: {
        status: 'fulfilled',
        fulfilledAt: new Date(),
        receiptUrls: receiptUrls || [],
        unitPriceActual: actualUnit,
        actualCost: actualUnit !== undefined && actualUnit !== null ? actualUnit * existing.quantityNeeded : null,
        surplusAction: surplusAction || null,
        surplusAmount: surplusQty || null,
        reallocatedTo: reallocation ? reallocation.targetId : null,
        flagForReview: surplusQty > 0 && surplusAction !== 'reallocated' ? true : undefined,
      },
    });
  }).catch((err) => {
    if (err.status) return err;
    throw err;
  });

  if (record.status === 400) return res.status(400).json({ message: record.message });
  if (record.flagForReview) {
    req.app.get('io')?.emit?.('procurement:flagForReview', { id: record.id, reference: record.reference });
  }
  req.app.get('io')?.emit?.('stockItems:updated', { id: record.itemId });
  await logAudit(req, 'Procurement Received', record.id, {
    reference: existing.reference,
    actualCost: record.actualCost,
    surplus: record.surplusAmount,
  });
  emitUpdate(req, record);
  res.json({ procurement: record });
};

export const cancelProcurement = async (req, res) => {
  const existing = await prisma.procurementRequisition.findUnique({ where: { id: req.params.id } });
  if (!existing) return res.status(404).json({ message: 'Procurement requisition not found' });
  if (['fulfilled', 'cancelled'].includes(existing.status)) {
    return res.status(400).json({ message: 'This requisition can no longer be cancelled' });
  }
  const record = await prisma.procurementRequisition.update({
    where: { id: existing.id },
    data: { status: 'cancelled' },
  });
  await logAudit(req, 'Procurement Cancelled', record.id, { reference: existing.reference }, 'Warning');
  emitUpdate(req, record);
  res.json({ procurement: record });
};

export const deleteProcurement = async (req, res) => {
  const existing = await prisma.procurementRequisition.findUnique({ where: { id: req.params.id } });
  if (!existing) return res.status(404).json({ message: 'Procurement requisition not found' });
  if (existing.status !== 'draft') {
    return res.status(400).json({ message: 'Only draft requisitions can be deleted' });
  }
  await prisma.procurementRequisition.delete({ where: { id: existing.id } });
  await logAudit(req, 'Procurement Deleted', existing.id, { reference: existing.reference }, 'Warning');
  req.app.get('io')?.emit?.('procurement:updated', { id: existing.id, deleted: true });
  res.json({ message: 'Procurement requisition deleted' });
};
