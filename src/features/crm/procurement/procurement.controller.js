const canEditDraft = (role) => ['admin', 'manager', 'kitchen_manager'].includes(role);

export const createProcurement = async (req, res) => {
  const { itemId, item, unit, quantityNeeded, neededBy, source } = req.body || {};
  if (!itemId || !item || !quantityNeeded || quantityNeeded <= 0) {
    return res.status(400).json({ message: 'itemId, item and a positive quantityNeeded are required' });
  }
  const reference = await makeReference();
  const record = await prisma.procurementRequisition.create({
    data: {
      reference,
      itemId,
      item,
      unit: unit || 'pieces',
      quantityNeeded,
      neededBy: neededBy ? new Date(neededBy) : null,
      source: source || null,
      createdById: req.userId,
      createdByName: req.userName,
    },
  });
  await logAudit(req, 'Procurement Created', record.id, { reference });
  emitUpdate(req, record);
  res.status(201).json({ procurement: record });
};

export const generateDrafts = async (req, res) => {
  const leadDays = Math.max(1, parseInt(req.body?.leadDays, 10) || 3);
  const created = await generateDraftRecords({ leadDays, userId: req.userId, userName: req.userName });
  for (const record of created) {
    await logAudit(req, 'Procurement Draft Generated', record.id, { reference: record.reference });
    emitUpdate(req, record);
  }
  res.status(201).json({ procurements: created, summary: { generated: created.length } });
};

export const autoGenerateDraftRecords = async ({ leadDays = 3, userId = null, userName = null } = {}) => {
  return generateDraftRecords({ leadDays, userId, userName });
};

const generateDraftRecords = async ({ leadDays, userId, userName }) => {
  const from = new Date();
  const to = new Date(Date.now() + leadDays * 86400000);

  const bookings = await prisma.booking.findMany({
    where: { status: 'Confirmed', checkIn: { gte: from, lte: to } },
    select: {
      id: true,
      checkIn: true,
      checkOut: true,
      adults: true,
      children: true,
      totalAmount: true,
    },
  });

  const bookingIds = bookings.map((b) => b.id);
  const forecastGuests = bookings.reduce((sum, b) => sum + (b.adults || 0) + (b.children || 0), 0);
  const forecastNights = bookings.reduce((sum, b) => {
    const days = Math.round((new Date(b.checkOut) - new Date(b.checkIn)) / 86400000);
    return sum + Math.max(days, 0);
  }, 0);
  const forecastAmount = bookings.reduce((sum, b) => sum + (b.totalAmount || 0), 0);
  const neededBy = bookings.length ? bookings[0].checkIn : new Date(to);

  const stockItems = await prisma.stockItem.findMany({
    where: { perishable: false },
  });
  const open = await prisma.procurementRequisition.findMany({
    where: { status: { in: ['draft', 'approved', 'ordered'] } },
    select: { itemId: true },
  });
  const openItems = new Set(open.map((r) => r.itemId));

  const created = [];
  for (const stock of stockItems) {
    if (openItems.has(stock.id)) continue;
    if (stock.parLevel <= 0) continue;
    if (stock.quantity >= stock.threshold) continue;
    const quantityNeeded = Math.max(stock.parLevel - stock.quantity, 1);
    const reference = await makeReference();
    const record = await prisma.procurementRequisition.create({
      data: {
        reference,
        itemId: stock.id,
        item: stock.item,
        unit: stock.unit,
        quantityNeeded,
        neededBy,
        status: 'draft',
        source: 'unresolved',
        bookingIds,
        forecastGuests,
        forecastNights,
        forecastAmount,
        createdById: userId,
        createdByName: userName,
      },
    });
    created.push(record);
  }

  return created;
};

export const updateProcurement = async (req, res) => {
  const existing = await prisma.procurementRequisition.findUnique({ where: { id: req.params.id } });
  if (!existing) return res.status(404).json({ message: 'Procurement requisition not found' });
  if (existing.status !== 'draft') {
    return res.status(400).json({ message: 'Only draft requisitions can be edited' });
  }
  if (!canEditDraft(req.role)) {
    return res.status(403).json({ message: 'Insufficient permissions to edit procurement requisitions' });
  }

  const data = {};
  if (req.body.quantityNeeded !== undefined) {
    if (req.body.quantityNeeded <= 0) return res.status(400).json({ message: 'quantityNeeded must be positive' });
    data.quantityNeeded = req.body.quantityNeeded;
  }
  if (req.body.neededBy !== undefined) data.neededBy = req.body.neededBy ? new Date(req.body.neededBy) : null;
  if (req.body.source !== undefined) data.source = req.body.source || null;
  if (req.body.unit !== undefined && req.body.unit) data.unit = req.body.unit;
  if (['admin', 'manager'].includes(req.role)) {
    if (req.body.farmCoverage !== undefined) data.farmCoverage = Math.max(0, parseInt(req.body.farmCoverage, 10) || 0);
    if (req.body.unitPriceEstimated !== undefined) data.unitPriceEstimated = req.body.unitPriceEstimated;
  }

  const record = await prisma.procurementRequisition.update({ where: { id: existing.id }, data });
  await logAudit(req, 'Procurement Updated', record.id, { reference: existing.reference, data });
  emitUpdate(req, record);
  res.json({ procurement: record });
};

