import { randomBytes } from 'node:crypto';
import prisma from '../../../lib/prisma.js';

const STATUSES = ['draft', 'approved', 'ordered', 'fulfilled', 'cancelled'];

const makeReference = async (retry = 0) => {
  const date = new Date().toISOString().slice(0, 10).replace(/-/g, '');
  const suffix = randomBytes(2).toString('hex').toUpperCase();
  const reference = `PRQ-${date}-${suffix}`;
  const existing = await prisma.procurementRequisition.findUnique({ where: { reference } });
  if (existing && retry < 3) return makeReference(retry + 1);
  return reference;
};

const logAudit = (req, action, entityId, changes, severity = 'Info') => {
  return prisma.auditLog.create({
    data: {
      action,
      entityType: 'Procurement',
      entityId,
      actorId: req.userId,
      changes,
      ipAddress: req.ip,
      userAgent: req.get('user-agent'),
      severity,
    },
  });
};

const emitUpdate = (req, record) => {
  req.app.get('io')?.emit?.('procurement:updated', record);
};

export const getProcurements = async (req, res) => {
  const { status, source, itemId, dateFrom, dateTo } = req.query;
  const where = {};
  if (status && STATUSES.includes(status)) where.status = status;
  if (source) where.source = source;
  if (itemId) where.itemId = itemId;
  if (dateFrom || dateTo) {
    where.createdAt = {};
    if (dateFrom) where.createdAt.gte = new Date(dateFrom);
    if (dateTo) where.createdAt.lte = new Date(dateTo);
  }
  const records = await prisma.procurementRequisition.findMany({
    where,
    orderBy: { createdAt: 'desc' },
  });
  res.json({ procurements: records });
};

